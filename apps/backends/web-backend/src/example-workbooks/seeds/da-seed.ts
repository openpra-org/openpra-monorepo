function pathForCode(code: string, hlr: HlrId): string {
  if (hlr === "A") return "componentBoundaries";
  if (hlr === "B") return "componentGroupings";
  if (code === "DA-D7" || code === "DA-D8" || code === "DA-D9") return "ccfParameterEstimations";
  if (hlr === "D") return "parameters";
  if (hlr !== "C") return "documentation";
  const n = Number(code.slice(4));
  if (n <= 2) return "sources";
  if (n <= 4) return "recordSets";
  if (n <= 6) return "failureEventClassifications";
  if (n <= 9 || n === 12) return "demandCounts";
  if (n <= 11) return "hourCounts";
  if (n <= 23 || n === 25) return "parameters";
  return "outages";
}

